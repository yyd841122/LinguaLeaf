// Expands named shared CSS fragments at the export's slots, preserving its
// cascade order, and resolves popup dimensions from the reading model.
import { build } from "esbuild";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const serverRoot = resolve(here, "..");
const repoRoot = resolve(serverRoot, "../..");
const source = resolve(
  repoRoot,
  "packages/reading-model/src/annotated-style.css"
);
const generated = resolve(serverRoot, "src/export/style.generated.ts");
const regenerate = "npm run build:export-style --workspace @lingualeaf/server";

const result = await build({
  absWorkingDir: repoRoot,
  entryPoints: [
    resolve(repoRoot, "packages/reading-model/src/popup-anchor.ts"),
  ],
  bundle: true,
  format: "esm",
  platform: "node",
  target: "es2017",
  charset: "utf8",
  write: false,
  logLevel: "silent",
  outfile: "popup-anchor.js",
});
const { POPUP_WIDTH_PX, POPUP_MAX_HEIGHT_PX, POPUP_MARGIN_PX } = await import(
  `data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString("base64")}`
);

function readCss(path) {
  const css = readFileSync(path, "utf8");
  // CSS rides inside an HTML raw-text element. Even a comment containing
  // this sequence would close the style tag early; check every source.
  if (/<\/style/i.test(css)) {
    throw new Error(`${path} contains </style — refusing to inline it`);
  }
  return css;
}

function assembleStyle() {
  const css = readCss(source);
  const imported = css.match(/^@import "(\.\/[^"\n]+)";\s*\n/);
  if (!imported) throw new Error("expected a leading shared CSS import");
  const shared = readCss(resolve(dirname(source), imported[1]));

  // The shared file is ordinary CSS. These comments name fragments only;
  // the export's matching comments determine their cascade positions.
  const fragments = new Map();
  for (const match of shared.matchAll(
    /\/\* @shared ([\w-]+) \*\/\n([\s\S]*?)(?=\/\* @shared |$)/g
  )) {
    if (fragments.has(match[1])) {
      throw new Error(`duplicate shared CSS fragment: ${match[1]}`);
    }
    fragments.set(match[1], match[2].trim());
  }
  const used = new Set();
  let style = css
    .slice(imported[0].length)
    .replace(/\/\* @shared ([\w-]+) \*\//g, (_, name) => {
      if (!fragments.has(name) || used.has(name)) {
        throw new Error(`missing or repeated shared CSS fragment: ${name}`);
      }
      used.add(name);
      return fragments.get(name);
    });
  for (const name of fragments.keys()) {
    if (!used.has(name)) throw new Error(`unused shared CSS fragment: ${name}`);
  }

  const tokens = {
    __POPUP_WIDTH_REM__: `${POPUP_WIDTH_PX / 16}rem`,
    __POPUP_MAX_HEIGHT_REM__: `${POPUP_MAX_HEIGHT_PX / 16}rem`,
    __POPUP_MARGIN_TWICE_REM__: `${(POPUP_MARGIN_PX * 2) / 16}rem`,
  };
  for (const [token, value] of Object.entries(tokens)) {
    if (!style.includes(token)) throw new Error(`missing CSS token: ${token}`);
    style = style.replaceAll(token, value);
  }
  if (/@import\b|__POPUP_\w+__/.test(style)) {
    throw new Error("unresolved CSS import or popup token");
  }
  return style.trim();
}

try {
  const style = assembleStyle();
  const output = `// Generated by apps/server/scripts/build-export-style.mjs from
// packages/reading-model/src/annotated-style.css — do not edit by hand.
// Regenerate: ${regenerate}
export const EXPORT_STYLE = ${JSON.stringify(style)};
`;
  if (process.argv.includes("--check")) {
    if (!existsSync(generated) || readFileSync(generated, "utf8") !== output) {
      console.error(`style.generated.ts is stale.\nRun: ${regenerate}`);
      process.exit(1);
    }
    console.log("style.generated.ts is fresh");
  } else {
    writeFileSync(generated, output);
    console.log("style.generated.ts written");
  }
} catch (error) {
  console.error(`build-export-style: ${error.message}`);
  process.exit(1);
}
